// Generates clients/python/allocyn_api.py from the API's route table, so the Python client can never
// fall behind the API. `node scripts/gen-python-client.mjs` writes it; `--check` fails if it is out of date.
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL, fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const { ROUTES } = await import(pathToFileURL(path.join(root, "packages/api/src/routes.ts")).href);
const out = path.join(root, "clients/python/allocyn_api.py");

const snake = (s) => s.replace(/([A-Z])/g, "_$1").toLowerCase();
const first = (s) => s.split(/(?<=\.)\s/)[0].replace(/`/g, "");
const pyType = (t) => (t === "integer" ? "int" : t === "boolean" ? "bool" : "str");

const methods = ROUTES.map((r) => {
  const method = snake(r.operationId);
  const pathArgs = r.pathParams.map((p) => ({ name: snake(p.name), api: p.name, type: p.schema.type === "integer" ? "int" : "str" }));
  const queryArgs = [
    ...(r.chainRead ? [{ name: "consistency", api: "consistency", type: "str", doc: '"latest" or "final" (default: the client\'s)' }] : []),
    ...(r.deep ? [{ name: "deep", api: "deep", type: "bool", doc: "also read the contract once" }] : []),
    ...(r.query ?? []).map((q) => ({ name: snake(q.name), api: q.name, type: pyType(q.schema.type), doc: q.description.replace(/`/g, "") })),
  ];
  const sig = ["self", ...pathArgs.map((a) => `${a.name}: ${a.type}`), ...(queryArgs.length ? ["*", ...queryArgs.map((a) => `${a.name}: Optional[${a.type}] = None`)] : [])].join(", ");
  const urlPath = r.path.replace(/\{(\w+)\}/g, (_, n) => `{_q(${snake(n)})}`);
  const ret = r.contentType ? "str" : "Any";
  const lines = [
    `    def ${method}(${sig}) -> ${ret}:`,
    `        """${first(r.summary)}. ${first(r.description)}"""`,
    `        return self._get(f"${urlPath}", {${queryArgs.map((a) => `"${a.api}": ${a.name}`).join(", ")}}${r.contentType ? ", raw=True" : ""})`,
  ];
  return lines.join("\n");
}).join("\n\n");

const src = `# GENERATED by scripts/gen-python-client.mjs from the Allocyn API route table. Do not edit by hand.
"""Allocyn API client for Python. Standard library only, read-only.

    from allocyn_api import AllocynApi
    api = AllocynApi("https://your-project.vercel.app")
    job = api.get_job("job-1")

Every method returns the \`data\` of the API's answer, or raises AllocynApiError with the API's error code.
It cannot write: writes are signed by the participant's own wallet with @allocyn/sdk.
"""
import json
import urllib.error
import urllib.parse
import urllib.request
from typing import Any, Optional

__version__ = "0.1.0"


class AllocynApiError(Exception):
    """The API answered with an error (or something that is not the Allocyn API)."""

    def __init__(self, status: int, code: str, message: str, retryable: bool = False, field: Optional[str] = None):
        super().__init__(f"{code}: {message}")
        self.status, self.code, self.message, self.retryable, self.field = status, code, message, retryable, field


def _q(value: Any) -> str:
    return urllib.parse.quote(str(value), safe="")


class AllocynApi:
    def __init__(self, base_url: str, *, consistency: Optional[str] = None, timeout: float = 40.0):
        parsed = urllib.parse.urlparse(base_url)
        if parsed.scheme not in ("http", "https") or not parsed.netloc:
            raise ValueError(f"{base_url!r} is not a valid URL")
        if parsed.scheme != "https" and parsed.hostname not in ("localhost", "127.0.0.1"):
            raise ValueError("The API URL must use https (http is only accepted for localhost).")
        if consistency not in (None, "latest", "final"):
            raise ValueError('consistency must be "latest" or "final"')
        self.base_url = base_url.rstrip("/")
        self.consistency = consistency
        self.timeout = timeout

    def _get(self, path: str, query: Optional[dict] = None, raw: bool = False) -> Any:
        params = {k: ("true" if v is True else "false" if v is False else v) for k, v in (query or {}).items() if v is not None}
        if "consistency" in (query or {}) and params.get("consistency") is None and self.consistency:
            params["consistency"] = self.consistency
        url = self.base_url + path + ("?" + urllib.parse.urlencode(params) if params else "")
        request = urllib.request.Request(url, headers={"Accept": "image/svg+xml" if raw else "application/json", "User-Agent": f"allocyn-api-python/{__version__}"})
        try:
            with urllib.request.urlopen(request, timeout=self.timeout) as response:
                status, body = response.status, response.read().decode("utf-8")
        except urllib.error.HTTPError as e:
            status, body = e.code, e.read().decode("utf-8", "replace")
        except urllib.error.URLError as e:
            raise AllocynApiError(0, "NETWORK_UNREACHABLE", f"Could not reach {self.base_url}: {e.reason}", retryable=True) from None
        if raw and status == 200:
            return body
        try:
            payload = json.loads(body)
        except ValueError:
            if raw:
                raise AllocynApiError(status, f"HTTP_{status}", "The API answered with an error badge (the job may not exist).") from None
            raise AllocynApiError(status, "NOT_ALLOCYN_API", f"The answer from {self.base_url} is not JSON. Is that the Allocyn API?") from None
        if not isinstance(payload, dict) or payload.get("success") is not True:
            err = (payload or {}).get("error", {}) if isinstance(payload, dict) else {}
            raise AllocynApiError(status, err.get("code", f"HTTP_{status}"), err.get("message", "The API reported an error."), bool(err.get("retryable", False)), err.get("field"))
        return payload["data"]

${methods}
`;

if (process.argv.includes("--check")) {
  const cur = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : null;
  if (cur !== src) { console.error("clients/python/allocyn_api.py is missing or out of date. Run `node scripts/gen-python-client.mjs`."); process.exit(1); }
  console.log("Python client is up to date");
} else {
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, src);
  console.log("wrote clients/python/allocyn_api.py");
}
