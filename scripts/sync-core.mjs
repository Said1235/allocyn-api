// Copies the parity-tested contract core from the Allocyn web app into the SDK.
//
//   node scripts/sync-core.mjs          copy (overwrites packages/sdk/src/core)
//   node scripts/sync-core.mjs --check  exit 1 if the copy differs from the app's source
//
// The web app (boilerplate/frontend/lib) is the source of truth for the contract rules: text
// cleaning, link checks, hashes, strict parsing, the transaction lifecycle and the on-chain
// repository. The SDK carries a generated copy so it can be published on its own. Never edit
// packages/sdk/src/core by hand: change the app's source, run this script, run the tests.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = process.env.ALLOCYN_APP_LIB ?? path.resolve(root, "../boilerplate/frontend/lib");
const APP = path.resolve(SRC, "..");
const DST = path.join(root, "packages/sdk/src/core");
const check = process.argv.includes("--check");

const FILES = [
  "contract/canonical.ts", "contract/chain-repository.ts", "contract/errors.ts", "contract/gateway.ts",
  "contract/parse.ts", "contract/pending.ts", "contract/python-text.ts", "contract/sdk-gateway.ts",
  "contract/sim.ts", "contract/spec.ts", "contract/tx.ts", "contract/url.ts",
  "domain/rules.ts", "domain/types.ts", "domain/validation.ts",
  "repo/types.ts", "wallet/address.ts",
];
const TESTS = ["contract/chain-repository.test.ts", "contract/parity.test.ts", "domain/validation.test.ts"];
const EXTRA = [
  { from: path.join(SRC, "contract/fixtures/parity.json"), to: "contract/fixtures/parity.json", raw: true },
];
const VENDORED_CONTRACT = { from: path.join(APP, "contract/smart_agreement.py"), to: path.join(root, "packages/sdk/contract/smart_agreement.py") };
const FIXTURE_GEN = { from: path.join(APP, "scripts/gen-parity-fixtures.py"), to: path.join(root, "packages/sdk/scripts/gen-parity-fixtures.py") };

const HEADER = "// GENERATED by scripts/sync-core.mjs from the Allocyn web app (boilerplate/frontend/lib). Do not edit here.\n";
const SHIM_TYPES = HEADER + "// Only the storage contract the pending-transaction store needs (the app's wallet/types.ts is UI-specific).\nexport interface KeyValueStorage {\n  getItem(key: string): string | null;\n  setItem(key: string, value: string): void;\n  removeItem(key: string): void;\n}\n";

const out = new Map(); // destination path -> content
for (const f of FILES) out.set(path.join(DST, f), HEADER + fs.readFileSync(path.join(SRC, f), "utf8"));
for (const f of TESTS) {
  let s = fs.readFileSync(path.join(SRC, f), "utf8");
  s = s.replace('"../../contract/smart_agreement.py"', '"../../../contract/smart_agreement.py"');
  out.set(path.join(DST, f), HEADER + s);
}
for (const e of EXTRA) out.set(path.join(DST, e.to), fs.readFileSync(e.from, "utf8"));
out.set(path.join(DST, "wallet/types.ts"), SHIM_TYPES);
out.set(VENDORED_CONTRACT.to, fs.readFileSync(VENDORED_CONTRACT.from, "utf8"));
out.set(FIXTURE_GEN.to, fs.readFileSync(FIXTURE_GEN.from, "utf8"));

let drift = 0;
for (const [dest, content] of out) {
  const cur = fs.existsSync(dest) ? fs.readFileSync(dest, "utf8") : null;
  if (cur === content) continue;
  drift++;
  if (check) { console.error("differs:", path.relative(root, dest)); continue; }
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.writeFileSync(dest, content);
}
if (check) {
  if (drift) { console.error(`${drift} file(s) differ from the web app. Run: node scripts/sync-core.mjs`); process.exit(1); }
  console.log(`core is in sync (${out.size} files)`);
} else console.log(`synced ${out.size} files (${drift} changed)`);
